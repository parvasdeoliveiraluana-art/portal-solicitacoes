function abrirFormulario(tipo) {

    if (tipo === "espresso") {
        window.location.href = "formularios/espresso.html";
    }

    else if (tipo === "uber") {
        window.location.href = "formularios/uber.html";
    }

    else if (tipo === "webfrota") {
        window.location.href = "formularios/webfrota.html";
    }

}
